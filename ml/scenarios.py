def _largest_remainder(weights: np.ndarray, total: int) -> np.ndarray:
    """Allocate ``total`` integer units in proportion to ``weights``.

    Uses the largest-remainder method so the allocation sums exactly to
    ``total`` and is stable under ties (``argsort`` with ``kind='stable'``).
    """
    w = np.asarray(weights, dtype=float)
    s = float(w.sum())
    if s <= 0.0:
        raise ValueError("weights must have a positive sum")
    raw = w / s * total
    base = np.floor(raw).astype(np.int64)
    shortfall = total - int(base.sum())
    if shortfall > 0:
        order = np.argsort(-(raw - base), kind="stable")
        base[order[:shortfall]] += 1
    return base


def _round_amount(poisha: float, rng: np.random.Generator) -> int:
    """Round a monetary value to a realistic denomination.

    Real transfers cluster on round numbers. The mixture below produces a
    spread of ৳1, ৳10 and ৳50 granularity, which also means amount values
    collide often enough to make exact-value rules useless.
    """
    draw = rng.random()
    if draw < 0.42:
        step = 5_000  # 50 BDT
    elif draw < 0.72:
        step = 1_000  # 10 BDT
    else:
        step = 100  # 1 BDT
    return max(step, int(round(poisha / step)) * step)


def _draw_amount(
    rng: np.random.Generator,
    txn_type: str,
    scale: float = 1.0,
    sigma: float | None = None,
) -> int:
    """Draw a plausible amount in integer poisha for a transaction type."""
    median_bdt, default_sigma, lo_bdt, hi_bdt = AMOUNT_MODEL[txn_type]
    sigma = default_sigma if sigma is None else sigma
    median_poisha = median_bdt * 100.0 * scale
    value = float(rng.lognormal(mean=math.log(max(median_poisha, 1.0)), sigma=sigma))
    lo = lo_bdt * 100.0
    hi = hi_bdt * 100.0
    value = min(max(value, lo), hi)
    return _round_amount(value, rng)


def _day_start_utc(day_index: int) -> int:
    """Return the UTC epoch second at which a local day begins."""
    return SIM_START_UTC_EPOCH + day_index * SECONDS_PER_DAY


def _local_date(day_index: int) -> _dt.date:
    """Return the local calendar date of a synthetic day index."""
    return SIM_START_LOCAL_DATE + _dt.timedelta(days=day_index)


def _haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Great-circle distance in kilometres between two synthetic points."""
    radius = 6371.0088
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = p2 - p1
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * radius * math.asin(math.sqrt(a))


def build_locations() -> tuple[Location, ...]:
    """Build the synthetic location reference table.

    Coordinates are derived from the region centroid plus a deterministic
    offset so that the table is independent of the random seed.
    """
    locations: list[Location] = []
    for region in REGIONS:
        base_lat, base_lon = REGION_CENTROIDS[region]
        for i, area in enumerate(AREAS[region]):
            dlat = ((i * 7) % 11 - 5) * 0.0135
            dlon = ((i * 5) % 13 - 6) * 0.0121
            slug = area.replace(" ", "-")
            locations.append(
                Location(
                    location_id=f"{region}.{slug}",
                    region=region,
                    area=area,
                    latitude=round(base_lat + dlat, 6),
                    longitude=round(base_lon + dlon, 6),
                )
            )
    return tuple(locations)


