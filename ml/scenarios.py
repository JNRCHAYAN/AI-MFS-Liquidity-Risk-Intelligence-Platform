@dataclass(frozen=True)
class SimConfig:
    """Everything that determines a generated world.

    Attributes:
        seed: Master random seed. Same seed plus same fields equals same
            world, byte for byte.
        n_wallets: Number of customer wallets.
        n_merchants: Number of merchant entities.
        n_agents: Number of agent entities.
        n_transactions: Target total number of transactions. The realised
            total is exact unless the requested total is too small to hold
            the fraud budget, in which case it is reported honestly.
        days: Length of the synthetic window in local days.
    """

    seed: int = 42
    n_wallets: int = 1_000
    n_merchants: int = 50
    n_agents: int = 30
    n_transactions: int = 60_000
    days: int = 90

    def __post_init__(self) -> None:
        if self.n_wallets < 10:
            raise ValueError("n_wallets must be at least 10")
        if self.n_merchants < 3:
            raise ValueError("n_merchants must be at least 3")
        if self.n_agents < 2:
            raise ValueError("n_agents must be at least 2")
        if self.n_transactions < 100:
            raise ValueError("n_transactions must be at least 100")
        if self.days < 7:
            raise ValueError("days must be at least 7")

    @classmethod
    def small(cls, seed: int = 7) -> SimConfig:
        """Return a fast preset for tests and CI (low thousands of rows)."""
        return cls(
            seed=seed,
            n_wallets=60,
            n_merchants=8,
            n_agents=5,
            n_transactions=2_000,
            days=30,
        )


