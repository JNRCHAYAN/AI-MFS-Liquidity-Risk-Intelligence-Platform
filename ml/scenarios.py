"""Synthetic mobile-financial-services scenario library for upay Shield.

This module builds a fully synthetic, reproducible world of customers
(wallets), merchants and agents, plus the transactions, device records and
login events they produce. It exists so that the risk pipeline can be
developed and evaluated on data with a *known* but non-trivial structure.

Design commitments (see ``AGENTS.md`` and ``docs/architecture.md``):

* **Synthetic only.** No real names, phone numbers, account numbers or any
  other personal data are produced. Identifiers are opaque counters.
* **Deterministic.** All randomness flows from one seeded
  :class:`numpy.random.Generator`. The same :class:`SimConfig` produces the
  same world, byte for byte.
* **Money is integer poisha.** 1 BDT = 100 poisha. No monetary value in this
  module is ever a float.
* **Timestamps are UTC.** Every emitted timestamp is an integer epoch second
  that is converted to a timezone-aware UTC timestamp at the end. Behavioural
  hour-of-day is generated in Asia/Dhaka (a fixed UTC+06:00 offset; Bangladesh
  has no daylight saving) and stored as UTC.
* **Overlapping distributions.** Fraud is generated by rich, multi-event
  stochastic processes, not by a threshold. Normal activity deliberately
  contains high-value, bursty and new-device behaviour (the benign
  confounders) so that no simple rule separates the classes.
* **Labels are quarantined.** Ground truth is written only to the
  ``scenario_truth`` frame, keyed by transaction id. It is never a column of
  the transactions frame.

The public entry point is :func:`build_world`.
"""

